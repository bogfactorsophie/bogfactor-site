#!/usr/bin/env node
// One-off migration: radio/shows.json -> D1 SQL + R2 upload script.
//
// Usage:
//   node tools/migrate-json-to-d1.mjs
//
// Produces:
//   tools/out/migration.sql          INSERTs for shows + tracks
//   tools/out/upload-images.sh       wrangler r2 commands for each image
//   tools/out/image-map.json         { sourcePath: r2Key } for reference
//
// Then run:
//   wrangler d1 execute bogfactor --remote --file=tools/out/migration.sql
//   bash tools/out/upload-images.sh

import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve, extname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'tools', 'out');
const SHOWS_PATH = resolve(ROOT, 'radio', 'shows.json');
const BUCKET = 'bogfactor-show-images';

const MIME_BY_EXT = {
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  png: 'image/png',
  webp: 'image/webp',
  gif: 'image/gif',
  avif: 'image/avif',
};

const sqlEscape = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const splitTrack = (line) => {
  const t = String(line).trim();
  const idx = t.indexOf(' - ');
  if (idx === -1) return { title: t, artist: '' };
  return { title: t.slice(0, idx).trim(), artist: t.slice(idx + 3).trim() };
};

// Tracklist convention is "Title - Artist". The form placeholder confirms this.
// Some seed rows may have it the other way around — we accept what's there and
// can fix individual rows in the admin UI after migration.

// Translate the seed "YYYY-MM" into an ISO timestamp. We don't know the day,
// so default to the first Friday of the month at 13:00 UK time (the regular
// live slot). Hand-edit aired_at afterwards for any one-off shows (e.g. the
// morning shows) where you remember the exact date.
const firstFridayIsoUtc = (year, month) => {
  // month 1-12
  const d = new Date(Date.UTC(year, month - 1, 1, 13, 0, 0));
  const dow = d.getUTCDay(); // 0=Sun..6=Sat, 5=Fri
  const add = (5 - dow + 7) % 7;
  d.setUTCDate(1 + add);
  return d.toISOString();
};

async function fileToR2Key(localPath) {
  const buf = await readFile(localPath);
  const hash = createHash('sha256').update(buf).digest('hex');
  let ext = extname(localPath).slice(1).toLowerCase();
  if (ext === 'jpeg') ext = 'jpg';
  if (!ext) ext = 'bin';
  return { key: `${hash}.${ext}`, ext, mime: MIME_BY_EXT[ext] || 'application/octet-stream' };
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const raw = await readFile(SHOWS_PATH, 'utf8');
  const shows = JSON.parse(raw);

  // D1's remote executor wraps statements in its own transaction and rejects
  // explicit BEGIN/COMMIT, so we don't emit them here.
  const sqlLines = [
    '-- Generated by tools/migrate-json-to-d1.mjs',
    '-- Run via: npx wrangler d1 execute bogfactor --remote --file=tools/out/migration.sql',
  ];
  const uploadCmds = ['#!/usr/bin/env bash', 'set -euo pipefail', ''];
  const imageMap = {};

  for (const show of shows) {
    const [yStr, mStr] = String(show.date || '').split('-');
    const year = Number(yStr);
    const month = Number(mStr);
    if (!year || !month) {
      console.warn(`skipping ${show.id}: bad date "${show.date}"`);
      continue;
    }
    const airedAt = firstFridayIsoUtc(year, month);

    let imageKey = null;
    if (show.image) {
      // Show images are referenced as "../assets/foo.jpg" relative to /radio/.
      const localPath = resolve(ROOT, 'radio', show.image);
      try {
        await stat(localPath);
        const { key, mime } = await fileToR2Key(localPath);
        imageKey = key;
        imageMap[show.image] = key;
        uploadCmds.push(
          `npx wrangler r2 object put ${BUCKET}/${key} --file="${localPath}" --content-type="${mime}" --remote`
        );
      } catch (err) {
        console.warn(`image missing for ${show.id}: ${localPath}`);
      }
    }

    sqlLines.push(
      `INSERT INTO shows (id, title, description, mixcloud_path, soundcloud_url,
                          aired_at, duration_min, producer, image_key, is_published)
       VALUES (${[
         sqlEscape(show.id),
         sqlEscape(show.title),
         sqlEscape(show.description),
         sqlEscape(show.mixcloudPath),
         sqlEscape(null),
         sqlEscape(airedAt),
         sqlEscape(null),
         sqlEscape(null),
         sqlEscape(imageKey),
         '1',
       ].join(', ')});`
    );

    const tracks = Array.isArray(show.tracklist) ? show.tracklist : [];
    tracks.forEach((line, idx) => {
      const { title, artist } = splitTrack(line);
      sqlLines.push(
        `INSERT INTO tracks (show_id, position, title, artist) VALUES (${[
          sqlEscape(show.id),
          idx + 1,
          sqlEscape(title),
          sqlEscape(artist),
        ].join(', ')});`
      );
    });
  }

  await writeFile(resolve(OUT_DIR, 'migration.sql'), sqlLines.join('\n') + '\n');
  await writeFile(resolve(OUT_DIR, 'upload-images.sh'), uploadCmds.join('\n') + '\n', { mode: 0o755 });
  await writeFile(resolve(OUT_DIR, 'image-map.json'), JSON.stringify(imageMap, null, 2) + '\n');

  console.log(`Wrote ${OUT_DIR}/migration.sql`);
  console.log(`Wrote ${OUT_DIR}/upload-images.sh`);
  console.log(`Shows: ${shows.length}, images mapped: ${Object.keys(imageMap).length}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
